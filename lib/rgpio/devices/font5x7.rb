    # Shown for anything outside printable ASCII: a hollow box.
    MISSING = [0x7f, 0x41, 0x41, 0x41, 0x7f].freeze

    # @return [Array<Integer>] the five column bytes for +char+
    def self.glyph(char)
      code = char.ord
      return MISSING unless code.between?(FIRST, FIRST + GLYPHS.size - 1)

      GLYPHS[code - FIRST]
    end

    # @return [Boolean] whether the pixel at column +x+, row +y+ of +char+ is set
    def self.set?(char, x, y)
      return false if x >= WIDTH || y >= HEIGHT

      glyph(char)[x][y] == 1
    end

    # Text in this font for any display with #fill_rect and #blit (and a
    # private #synchronize that holds its drawing lock).
    module Drawing
      # Draw text in the built-in 5x7 font (printable ASCII; anything else shows
      # as a box). "\n" starts a new line. With bg: nil only the strokes are drawn,
      # leaving what was underneath; with a background colour each character
      # cell is painted in full, which overwrites old text cleanly and is faster.
      # @return [Array(Integer, Integer)] width and height of what was drawn
      def text(x, y, str, color: :white, bg: nil, scale: 1)
        unless scale.is_a?(Integer) && scale.positive?
          raise ArgumentError,
                "scale must be a positive Integer, got #{scale.inspect}"
        end

        fg = RGB565.from(color)
        bg &&= RGB565.from(bg)
        lines = str.to_s.split("\n", -1)
        synchronize do
          lines.each_with_index do |line, i|
            line_y = y + (i * Font5x7::CELL_HEIGHT * scale)
            bg ? text_line_opaque(x, line_y, line, [fg, bg], scale) : text_line_transparent(x, line_y, line, fg, scale)
          end
        end
        text_size(str, scale: scale)
      end

      # @return [Array(Integer, Integer)] width and height #text would draw
      def text_size(str, scale: 1)
        lines = str.to_s.split("\n", -1)
        [lines.map(&:length).max.to_i * Font5x7::CELL_WIDTH * scale, lines.size * Font5x7::CELL_HEIGHT * scale]
      end

      private

      # One line in full: render every cell to a buffer, then send it at once.
      def text_line_opaque(x, y, line, colors, scale)
        return if line.empty?

        fg, bg = colors
        on = [fg].pack("n") * scale
        off = [bg].pack("n") * scale
        rows = Array.new(Font5x7::CELL_HEIGHT) do |row|
          line.each_char.map do |char|
            Array.new(Font5x7::CELL_WIDTH) { |col| Font5x7.set?(char, col, row) ? on : off }.join
          end.join * scale
        end
        w = line.length * Font5x7::CELL_WIDTH * scale
        blit(x, y, w, Font5x7::CELL_HEIGHT * scale, rows.join)
      end

      # Strokes only: one rectangle per horizontal run of set pixels.
      def text_line_transparent(x, y, line, fg, scale)
        line.each_char.with_index do |char, i|
          cell_x = x + (i * Font5x7::CELL_WIDTH * scale)
          Font5x7::HEIGHT.times do |row|
            runs(char, row).each do |start, length|
              fill_rect(cell_x + (start * scale), y + (row * scale), length * scale, scale, fg)
            end
          end
        end
      end

      # @return [Array<Array(Integer, Integer)>] [start column, length] of each run
      def runs(char, row)
        result = []
        Font5x7::WIDTH.times do |col|
          next unless Font5x7.set?(char, col, row)

          if result.last && result.last.sum == col
            result.last[1] += 1
          else
            result << [col, 1]
          end
        end
        result
      end
    end
